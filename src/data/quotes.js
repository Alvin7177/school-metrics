const QUOTE_INDEX_KEY = "schoolMetricsQuoteIndex";

export function getNextQuote() {
  let index = Number(localStorage.getItem(QUOTE_INDEX_KEY) || 0);
  const quote = QUOTES[index % QUOTES.length];
  localStorage.setItem(QUOTE_INDEX_KEY, String((index + 1) % QUOTES.length));
  return quote;
}

export function peekQuote() {
  const index = Number(localStorage.getItem(QUOTE_INDEX_KEY) || 0);
  return QUOTES[index % QUOTES.length];
}

export function getQuoteCount() {
  return QUOTES.length;
}
